import { expect, test } from "@playwright/test";

test.use({ viewport: { width: 1440, height: 960 } });
test("independent bars, cross-group movement, empty groups and mobile restoration", async ({ page }) => {
  await page.goto("/browser/fixture.html?case=workspace&lang=en");
  const launcher = page.getByRole("navigation", { name: "Launcher", exact: true });
  await launcher.getByRole("button", { name: "Open @cirno", exact: true }).click();
  await page.getByRole("button", { name: "Split view", exact: true }).click();
  const bars = page.locator(".workbench-group-bar");
  await expect(bars).toHaveCount(2);
  await expect(bars.nth(1).getByRole("tab")).toHaveCount(0);
  const from = (await bars.nth(0).getByRole("tab", { name: "@cirno", exact: true }).boundingBox())!;
  const to = (await bars.nth(1).boundingBox())!;
  await page.mouse.move(from.x + 35, from.y + from.height / 2);
  await page.mouse.down();
  await page.mouse.move(to.x + 80, to.y + to.height / 2, { steps: 12 });
  await page.mouse.up();
  await expect(bars.nth(0).getByRole("tab")).toHaveCount(0);
  await expect(bars.nth(1).getByRole("tab", { name: "@cirno" })).toHaveCount(1);
  // Opening another page goes into the focused right group.
  await launcher.getByRole("button", { name: "Open New conversation", exact: true }).click();
  await expect(bars.nth(1).getByRole("tab", { name: "Research worker", exact: true })).toBeVisible();
  await bars.nth(1).getByRole("button", { name: "Move to other tab group" }).click();
  await expect(bars.nth(0).getByRole("tab", { name: "Research worker", exact: true })).toBeVisible();
  const worker = page.locator('[data-fixture-session="websocket:worker"]');
  const cirno = page.locator('[data-fixture-session="websocket:b1ec9323-2155-5f24-bc56-1da2f59aeecb"]');
  await expect(worker).toBeVisible(); await expect(cirno).toBeVisible();
  await worker.getByRole("textbox").fill("Worker draft stays here");
  await cirno.getByRole("textbox").fill("Router draft stays here");
  await page.screenshot({ path: "/tmp/cirno-review83-tab-groups-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(bars).toHaveCount(1);
  await expect(page.getByRole("tabpanel").filter({ visible: true })).toHaveCount(1);
  await expect(cirno.getByRole("textbox")).toHaveValue("Router draft stays here");
  await page.getByRole("tab", { name: "Research worker", exact: true }).click();
  await expect(worker.getByRole("textbox")).toHaveValue("Worker draft stays here");
  await page.screenshot({ path: "/tmp/cirno-review83-tab-groups-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 960 });
  await expect(bars).toHaveCount(2);
  await expect(worker.getByRole("textbox")).toHaveValue("Worker draft stays here");
  await expect(cirno.getByRole("textbox")).toHaveValue("Router draft stays here");
  await bars.nth(1).getByRole("button", { name: "Close @cirno", exact: true }).click();
  await expect(bars).toHaveCount(2);
  await expect(bars.nth(1).getByRole("tab")).toHaveCount(0);
  await bars.nth(0).getByRole("button", { name: "Close Research worker", exact: true }).click();
  await expect(page.getByRole("tab")).toHaveCount(0);
  await expect(page.getByRole("tabpanel").filter({ visible: true })).toHaveCount(0);
  await page.reload();
  await expect(bars).toHaveCount(2);
  await expect(page.getByRole("tab")).toHaveCount(0);
  await launcher.getByRole("button", { name: "Open @cirno", exact: true }).click();
  await expect(page.getByRole("tab", { name: "@cirno" })).toHaveCount(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
