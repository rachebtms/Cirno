/** Messages contracts shared by the browser and its transports. */

import type {
  ContextCompaction,
  RetryStatus as WireRetryStatus,
} from "../../../packages/client-events/notifications";
import type { ToolProgressEvent, UIFileEdit } from "./activity";

export type Role = "user" | "assistant" | "tool" | "system";

/** "trace" rows are intermediate agent breadcrumbs (tool-call hints,
 * progress pings) that should not be rendered as conversational replies. */
export type MessageKind = "message" | "trace" | "compaction";

export interface UIContextCompaction extends ContextCompaction {
  /** Live wire transitions announce; hydrated transcript rows stay silent. */
  announce?: boolean;
  attempts?: ContextCompaction[];
}

export type UITurnPhase =
  | "user"
  | "reasoning"
  | "activity"
  | "answer"
  | "complete";

export type MessageDeliveryStatus = "sending" | "accepted" | "failed";

export type MessageDeliveryErrorKind =
  | "message_too_big"
  | "workspace_scope_rejected"
  | "turn_rejected";

/** One image attached to a UIMessage.
 *
 * ``url`` can arrive in three different shapes, which the bubble renders
 * identically:
 * - A ``data:image/...;base64,...`` URL generated by the Composer for the
 *   optimistic preview of an in-flight user turn. Self-contained, no
 *   lifecycle.
 * - A signed ``/v0/media/...`` URL attached to a historical user turn by
 *   the backend on session replay. Safe to drop into an ``<img src>``.
 * - Absent. The backend couldn't resolve a stored path (file moved,
 *   deleted, or pre-media-persistence session). The bubble shows a
 *   placeholder tile with ``name`` as the label.
 */
export interface UIImage {
  url?: string;
  name?: string;
}

export type UIMediaKind = "image" | "video" | "file";

export interface UIMediaAttachment {
  kind: UIMediaKind;
  url?: string;
  name?: string;
}

export interface UIInputOrigin {
  kind:
    | "heartbeat"
    | "scheduled_task"
    | "trigger"
    | "conversation"
    | "subagent"
    | "continuation"
    | "system"
    | "supervision";
  action?: string;
  values?: Record<string, string | number>;
  label: string;
  id?: string;
  session_key?: string;
  received_at?: string;
}

export interface UIMessageSource {
  kind: "cron" | "local_trigger" | "trigger" | string;
  label?: string;
}

export interface TurnUsage {
  prompt_tokens?: number;
  completion_tokens?: number;
  total_tokens?: number;
  cached_tokens?: number;
  cache_write_tokens?: number;
  context_tokens?: number;
  request_count?: number;
  estimated_tokens?: number;
  generation_ms?: number;
  measured_completion_tokens?: number;
  ttft_ms?: number;
  timed_requests?: number;
}

export type RoundUsage = TurnUsage;

export type SubagentTaskState =
  | "queued"
  | "running"
  | "stopping"
  | "done"
  | "incomplete"
  | "error"
  | "cancelled"
  | "interrupted";

export interface SubagentTaskSnapshot {
  task_id: string;
  revision?: number;
  origin_message_id: string | null;
  origin_turn_id: string | null;
  created_at: number;
  completed_at: number | null;
  label: string;
  task_description: string;
  state: SubagentTaskState;
  phase: string;
  elapsed_seconds: number;
  iteration: number;
  tool_events: { name: string; status: string }[];
  usage: Record<string, number | string | null> | null;
  receipts: Record<string, "accepted" | "delivered" | "undelivered">;
  result: string | null;
  partial: boolean;
  stop_reason: string | null;
  error: string | null;
}

export interface SubagentTasksPayload {
  tasks: SubagentTaskSnapshot[];
}

export interface ResponseSource {
  provider: string;
  model: string;
  preset: string;
  fallback?: boolean;
}

export interface UITraceDetail {
  ref: string;
  bytes: number;
  traceCount: number;
}

export interface RetryStatus extends WireRetryStatus {
  next_retry_at?: number;
  turn_id?: string;
}

export interface UserQuestion {
  id: string;
  question: string;
  options: string[];
  assumption: string;
}

export interface UIMessage {
  userQuestion?: UserQuestion;
  questionCancellation?: { id: string; reason: string };
  id: string;
  role: Role;
  content: string;
  /** Literal output bypasses Markdown and content-based reply recognition. */
  renderAs?: "text";
  /** Invocation-time snapshots, never resolved from today's model presets. */
  responseSources?: ResponseSource[];
  kind?: MessageKind;
  isStreaming?: boolean;
  createdAt: number;
  /** For trace rows: each individual hint line, so consecutive hints can
   * render as a single collapsible group. */
  traces?: string[];
  /** Structured tool events behind trace rows. Kept so activity cards can
   * distinguish running, completed, and failed tool phases. */
  toolEvents?: ToolProgressEvent[];
  /** Oversized persisted trace content that can be fetched when activity is expanded. */
  traceDetail?: UITraceDetail;
  /** Activity rows: explicit file edits emitted by edit tools. */
  fileEdits?: UIFileEdit[];
  /** Activity rows created during the same agent phase share one collapsible block. */
  activitySegmentId?: string;
  /** Internal projection marker for assistant text emitted before a later tool.
   * It is not a wire message and is rendered as a compact activity row. */
  activityKind?: "model";
  /** Context-compaction lifecycle rendered as a standalone channel notice. */
  compaction?: UIContextCompaction;
  /** Display-only localization marker for fixed /compact command replies. */
  compactReply?: "empty" | "failed";
  /** User turn: optimistic blob URLs for preview. Replay: placeholder chips. */
  images?: UIImage[];
  /** Signed or local UI-renderable media attachments. */
  media?: UIMediaAttachment[];
  /** App-specific CLI adapters explicitly attached to this user turn. */
  cliApps?: UICliAppAttachment[];
  /** Settings-managed MCP presets explicitly attached to this user turn. */
  mcpPresets?: UIMcpPresetAttachment[];
  /** Persisted sessions explicitly referenced by this user turn. */
  sessionMentions?: SessionMention[];
  /** Assistant turn: accumulated model reasoning / thinking text. Built up
   * incrementally from ``reasoning_delta`` frames; finalized when
   * ``reasoning_end`` arrives. */
  reasoning?: string;
  /** True while ``reasoning_delta`` frames are still arriving for this turn.
   * Drives the shimmer header on ``ReasoningBubble``. */
  reasoningStreaming?: boolean;
  /** End-to-end wall time for this assistant turn (persisted ``latency_ms`` / ``turn_end``). */
  latencyMs?: number;
  /** Client epoch milliseconds when the definitive ``turn_end`` was received. */
  completedAt?: number;
  /** Additive model usage for this turn; context_tokens is the final request only. */
  usage?: TurnUsage;
  /** Logical model rounds in display order; runner-level recovery calls are aggregated. */
  roundUsages?: RoundUsage[];
  /** Configured context-window capacity for the model used by this turn. */
  contextWindowTokens?: number;
  idleCompactPercent?: number | null;
  idleCompactKeepPercent?: number | null;
  /** Lightweight provenance for proactive assistant messages. */
  source?: UIMessageSource;
  /** Structured provenance for a message delivered by another session. */
  sessionMessage?: UISessionMessage;
  inputOrigin?: UIInputOrigin;
  /** Stable protocol metadata for grouping all activity emitted by one user turn. */
  turnId?: string;
  turnPhase?: UITurnPhase;
  turnSeq?: number;
  /** First contributing sequence; later content/source updates do not move this row. */
  projectionStartSeq?: number;
  /** Phase-qualified stream ownership survives memory-cache restoration. */
  streamId?: string;
  reasoningStreamId?: string;
  /** Ephemeral delivery lifecycle for optimistic user messages. */
  deliveryStatus?: MessageDeliveryStatus;
  /** Structured rejection reason shown with a failed optimistic message. */
  deliveryErrorKind?: MessageDeliveryErrorKind;
}

export interface UICliAppAttachment {
  name: string;
  display_name?: string;
  category?: string;
  entry_point?: string;
  logo_url?: string | null;
  brand_color?: string | null;
}

export interface UIMcpPresetAttachment {
  name: string;
  display_name?: string;
  category?: string;
  transport?: string;
  status?: string;
  configured?: boolean;
  logo_url?: string | null;
  brand_color?: string | null;
}

export interface SessionMention {
  /** Stable public identity. Older transcript rows may not include it. */
  id?: string;
  /** Text token inserted in the composer, without the leading @. */
  name: string;
  /** Stable persisted-session identifier used by read_session. */
  session_key: string;
  title: string;
}

/** Stable public handle returned by the session-list endpoint. */
export interface SessionHandle {
  id: string;
  name: string;
}

export interface UISessionMessage {
  message_id: string;
  session: SessionHandle;
}

/** Local draft/preview data, converted to HTTP binary before sending a message.
 *
 * ``data_url`` must use a server-whitelisted image, video, or document MIME
 * type. SVG remains rejected on ingress to avoid an embedded-script XSS
 * surface. ``name`` is advisory and is surfaced as the placeholder label when
 * the session is replayed.
 */
export type OutboundMedia =
  import("../../../packages/client-events/attachments").DraftAttachment;

export interface OutboundCliAppMention {
  name: string;
  display_name?: string;
  category?: string;
  entry_point?: string;
  logo_url?: string | null;
  brand_color?: string | null;
}

export interface OutboundMcpPresetMention {
  name: string;
  display_name?: string;
  category?: string;
  transport?: string;
  status?: string;
  configured?: boolean;
  logo_url?: string | null;
  brand_color?: string | null;
}
