import { expect, test } from "@playwright/test";
import { switchControl } from "./control-driver";

for (const width of [390, 1440]) for (const theme of ["light", "dark"]) {
  test(`SSH Node enrollment and direct execution at ${width}px in ${theme}`, async ({ page }, info) => {
    const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
    await page.setViewportSize({ width, height: 900 });
    await page.goto(`/browser/fixture.html?case=nodes-rebuild&lang=en&theme=${theme}`);
    await page.getByRole("button", { name: "Execute command", exact: true }).click();
    const command = page.getByRole("dialog");
    await command.getByRole("textbox", { name: /^Command/ }).fill("true");
    await command.getByRole("button", { name: "Run", exact: true }).click();
    await expect(command.getByRole("status")).toContainText("Command completed");
    await command.getByRole("button", { name: "Close", exact: true }).last().click();
    await page.getByRole("button", { name: "Add Node", exact: true }).click();
    const form = page.getByRole("dialog", { name: "Add Node", exact: true });
    await expect(form.getByRole("textbox", { name: /^Password/ })).toHaveCount(0);
    await form.getByRole("button", { name: /SSH credential/ }).click();
    await page.getByRole("option", { name: "Available SSH", exact: true }).click();
    await form.getByRole("textbox", { name: /^Remote working directory/ }).fill("/new-research");
    await form.getByRole("button", { name: "Save", exact: true }).click();
    await expect(form.getByRole("alert")).toContainText("Fixture Node save failed");
    await expect(form.getByRole("textbox", { name: /^Remote working directory/ })).toHaveValue("/new-research");
    await form.getByRole("button", { name: "Save", exact: true }).click();
    await expect(form).not.toBeVisible();
    const row = page.locator(".node-list li").filter({ has: page.getByText("Available SSH", { exact: true }) });
    await row.getByRole("button", { name: "Execute command", exact: true }).click();
    await page.getByRole("textbox", { name: /^Command/ }).fill("uname -a");
    await page.getByRole("button", { name: "Run", exact: true }).click();
    await expect(page.getByRole("dialog").getByRole("status")).toContainText("Linux research-node");
    await page.screenshot({ path: info.outputPath("node-command.png"), animations: "disabled" });
    expect(errors).toEqual([]);
  });

  test(`SSH Credentials stay private until selected at ${width}px in ${theme}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(`/browser/fixture.html?case=nodes-rebuild&lang=en&theme=${theme}`);
    await page.getByRole("button", { name: "Manage credentials", exact: true }).click();
    await page.getByRole("button", { name: "Add record", exact: true }).click();
    await page.getByRole("textbox", { name: /^Label/ }).fill("GPU credential");
    await page.getByRole("button", { name: /Record type/ }).click();
    await page.getByRole("option", { name: "SSH", exact: true }).click();
    await expect(page.getByRole("switch", { name: "Add to SSH Nodes", exact: true })).not.toBeChecked();
    await expect(page.getByRole("switch", { name: "Available to Agent", exact: true })).not.toBeChecked();
    await page.getByRole("textbox", { name: /^Host\s*\*?$/ }).fill("gpu.example.test");
    await page.getByRole("textbox", { name: /^SSH username/ }).fill("researcher");
    await page.getByRole("button", { name: /Authentication/ }).click();
    await page.getByRole("option", { name: "Password", exact: true }).click();
    await page.locator('input[type="password"]').fill("fixture-private-password");
    const port = page.getByRole("spinbutton", { name: /^SSH port/ });
    await port.fill("0"); await page.getByRole("button", { name: "Save", exact: true }).click();
    await expect(port).toHaveAttribute("aria-invalid", "true");
    await port.fill("2222");
    await page.getByRole("button", { name: "Read host fingerprints", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("SHA256:fixture-host-key");
    await page.getByRole("button", { name: "Save", exact: true }).click();
    await expect(page.getByRole("alert")).toContainText("Fixture credential save failed");
    await expect(page.locator('input[type="password"]')).toHaveValue("fixture-private-password");
    await page.getByRole("button", { name: "Save", exact: true }).click();
    await expect(page.locator(".credential-editor")).toHaveCount(0);
    await page.getByRole("button", { name: "Manage Nodes", exact: true }).click();
    await expect(page.locator(".node-list li").filter({ hasText: "GPU credential" })).toHaveCount(0);
    await page.getByRole("button", { name: "Manage credentials", exact: true }).click();
    await page.locator(".credential-records").getByRole("button", { name: /GPU credential/ }).click();
    await expect(page.getByRole("textbox", { name: /^Host\s*\*?$/ })).toHaveValue("gpu.example.test");
    await expect(page.locator('input[type="password"]')).toHaveValue("");
    await switchControl(page, "Add to SSH Nodes").click();
    await switchControl(page, "Available to Agent").click();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath("ssh-credentials.png"), fullPage: true, animations: "disabled" });
    await page.getByRole("button", { name: "Save", exact: true }).click();
    await page.getByRole("button", { name: "Manage Nodes", exact: true }).click();
    const row = page.locator(".node-list li").filter({ hasText: "GPU credential" });
    await expect(row).toContainText("researcher@gpu.example.test:2222");
    await row.getByRole("button", { name: "Remove from Nodes", exact: true }).click();
    await expect(row).toHaveCount(0);
    await page.getByRole("button", { name: "Manage credentials", exact: true }).click();
    await expect(page.locator(".credential-records").getByRole("button", { name: /GPU credential/ })).toBeVisible();
  });
}
